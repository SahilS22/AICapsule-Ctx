import fs from 'node:fs';

const dir = 'node_modules/simple-icons/icons/';
const read = (f) => fs.readFileSync(dir + f + '.svg', 'utf8').match(/d="([^"]+)"/)[1];
const MOON = 'M21 12.8A9 9 0 1 1 11.2 3a7 7 0 0 0 9.8 9.8Z';

const map = {
  chatgpt: ['openai', '#10a37f'],
  claude: ['claude', '#d97757'],
  gemini: ['googlegemini', '#4285f4'],
  deepseek: ['openai', '#4d6bfe'],
  grok: ['x', '#000000'],
  perplexity: ['perplexity', '#20808d'],
  meta: ['meta', '#0064e0'],
  copilot: ['githubcopilot', '#1a1a1a'],
  mistral: ['openai', '#fa5306'],
  kimi: [MOON, '#2b2b72'],
  poe: ['poe', '#5d5fe3'],
  duckduckgo: ['duckduckgo', '#de5833'],
};

const q = "'";
let out = '// Generated by scripts/gen-platform-icons.mjs from simple-icons (CC0). Do not edit by hand.\n';
out += "import type { PlatformId } from '../core/capsule/schema';\n\n";
out += 'export interface PlatformIcon { path: string; color: string }\n\n';
out += 'export const PLATFORM_ICONS: Partial<Record<PlatformId, PlatformIcon>> = {\n';
for (const [k, [slug, color]] of Object.entries(map)) {
  const d = slug.startsWith('M') ? slug : read(slug);
  out += `  ${k}: { path: ${q}${d}${q}, color: ${q}${color}${q} },\n`;
}
out += '};\n\n';
out += 'export const PLATFORM_LABELS: Partial<Record<PlatformId, string>> = {\n';
const labels = {
  chatgpt: 'ChatGPT', claude: 'Claude', gemini: 'Gemini', deepseek: 'DeepSeek',
  grok: 'Grok', perplexity: 'Perplexity', meta: 'Meta AI', copilot: 'Copilot',
  mistral: 'Le Chat', kimi: 'Kimi', poe: 'Poe', duckduckgo: 'DuckDuckGo AI',
};
for (const [k, v] of Object.entries(labels)) out += `  ${k}: ${q}${v}${q},\n`;
out += '};\n\n';
out += 'export function platformIconSvg(id: PlatformId, size = 18): string {\n';
out += '  const ic = PLATFORM_ICONS[id];\n';
out += "  if (!ic) return '';\n";
out += '  return ' +
  `\`<svg viewBox="0 0 24 24" width=\${size} height=\${size} aria-hidden="true"><path d="\${ic.path}" fill="\${ic.color}"/></svg>\`;` +
  '\n';
out += '}\n';

fs.writeFileSync('src/ui/platformIcons.ts', out);
console.log('WROTE src/ui/platformIcons.ts', out.length, 'bytes');
